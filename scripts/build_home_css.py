"""Flatten Home's canonical CSS sources; no runtime imports or new dependencies.

Two outputs preserve the existing external Swiper stylesheet's cascade position.
Run before collectstatic, or use --check to detect stale generated assets.
"""
from __future__ import annotations

import argparse
import os
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / 'static/css'
OUTPUTS = {
    'home-base.css': (
        'layers/01-foundation.css', 'layers/02-layout.css',
        'layers/03-components.css', 'layers/04-responsive.css',
        'layout/navbar/09-mobile-drawer.css', 'layout/navbar/10-logo.css',
        'layout/navbar/11-polish.css',
    ),
    'home-page.css': (
        'pages/home.bundle.css', 'components/project-carousel.css',
        'pages/home-screens.css', 'base/light-theme-fixes.css',
        'components/sections/09-heading-system.css', 'layout/footer/07-auth.css',
    ),
}
GENERATED = CSS / 'generated'
IMPORT = re.compile(r'@import\s+url\(\s*[\'"]?([^\'"\s)]+)[\'"]?\s*\)\s*;')
URL = re.compile(r'url\(\s*([\'"]?)([^\'"\s)]+)\1\s*\)')
COMMENT = re.compile(r'/\*.*?\*/', re.S)


def expand(entries, css_root=CSS):
    """Return source bodies in cascade order, deduplicating at their last use."""
    sources = []

    def visit(path, stack):
        path = path.resolve()
        if not path.is_relative_to(css_root.resolve()):
            raise ValueError(f'Import outside CSS sources: {path}')
        if path in stack:
            raise ValueError(f'CSS import cycle: {path}')
        text = path.read_text(encoding='utf-8-sig')
        # Imports must be local, unconditional, and precede declarations.
        text = COMMENT.sub('', text)
        cursor = 0
        for match in IMPORT.finditer(text):
            if text[cursor:match.start()].strip():
                raise ValueError(f'Unsupported import position: {path}')
            target = urlsplit(match[1])
            if target.scheme or target.netloc or target.path.startswith('/'):
                raise ValueError(f'Only local CSS imports are supported: {path}')
            visit(path.parent / unquote(target.path), (*stack, path))
            cursor = match.end()
        body = text[cursor:].strip()
        if '@import' in body or '@charset' in body:
            raise ValueError(f'Unsupported CSS directive: {path}')
        if body:
            sources.append((path, body))

    for entry in entries:
        visit(css_root / entry, ())
    last = {path: index for index, (path, _) in enumerate(sources)}
    return [(path, body) for index, (path, body) in enumerate(sources)
            if last[path] == index]


def render(entries, output, css_root=CSS):
    sources = expand(entries, css_root)
    parts = ['/* Generated by scripts/build_home_css.py; edit canonical sources. */']
    for path, body in sources:
        def rebase(match):
            value = match[2]
            parsed = urlsplit(value)
            if parsed.scheme or parsed.netloc or value.startswith(('/', '#', 'var(')):
                return match[0]
            target = (path.parent / unquote(parsed.path)).resolve()
            if not target.is_relative_to(css_root.parent.resolve()) or not target.is_file():
                raise ValueError(f'Missing or unsafe CSS asset: {path}: {value}')
            relative = Path(os.path.relpath(target, output.parent)).as_posix()
            suffix = ('?' + parsed.query if parsed.query else '')
            suffix += '#' + parsed.fragment if parsed.fragment else ''
            return f'url("{relative}{suffix}")'
        parts.append(f'/* Source: {path.relative_to(css_root).as_posix()} */\n'
                     + URL.sub(rebase, body))
    return '\n\n'.join(parts) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    contents = {name: render(entries, GENERATED / name)
                for name, entries in OUTPUTS.items()}
    # Never move shared rules across the external vendor stylesheet.
    groups = [{p for p, _ in expand(entries)} for entries in OUTPUTS.values()]
    if groups[0] & groups[1]:
        raise ValueError('CSS source shared across the vendor boundary')
    for name, text in contents.items():
        output = GENERATED / name
        if args.check:
            if not output.exists() or output.read_text(encoding='utf-8') != text:
                raise SystemExit(f'Stale bundle: {name}; run python scripts/build_home_css.py')
        else:
            GENERATED.mkdir(exist_ok=True)
            output.write_text(text, encoding='utf-8', newline='\n')
    print(f'OK: {len(contents)} Home CSS bundles; local imports resolved; assets validated.')


if __name__ == '__main__':
    main()
